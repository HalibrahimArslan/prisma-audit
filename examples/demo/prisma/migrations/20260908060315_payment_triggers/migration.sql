-- Payment -> payment_aud
CREATE OR REPLACE FUNCTION "prisma_audit_payment_aud"() RETURNS trigger
LANGUAGE plpgsql AS $prisma_audit$
DECLARE
  revision_id bigint;
  row_state   record;
  rev_type    "RevisionType";
BEGIN
  -- The runtime says so while it is writing the audit rows itself, which is
  -- what lets the triggers be installed before the build that relies on them.
  IF nullif(current_setting('prisma_audit.suppress', true), '') = 'on' THEN
    RETURN NULL;
  END IF;

  IF TG_OP = 'DELETE' THEN
    row_state := OLD;  -- after a delete there is no NEW left to read
    rev_type  := 'DELETE';
  ELSIF TG_OP = 'UPDATE' THEN
    row_state := NEW;
    rev_type  := 'UPDATE';
  ELSE
    row_state := NEW;
    rev_type  := 'INSERT';
  END IF;

  revision_id := "prisma_audit_revision"();

  INSERT INTO "payment_aud" (
    "revisionId", "revType", "id", "order_id", "amount", "status"
  )
  VALUES (
    revision_id, rev_type, row_state."id", row_state."order_id", row_state."amount", row_state."status"
  )
  -- A row touched twice in one revision keeps one audit record, holding the
  -- state it ended up in. Created and then changed stays an INSERT: that is
  -- what the revision did to it.
  ON CONFLICT ("revisionId", "id") DO UPDATE SET
    "revType" = CASE
                  WHEN "payment_aud"."revType" = 'INSERT'
                   AND excluded."revType" = 'UPDATE'
                  THEN 'INSERT'::"RevisionType"
                  ELSE excluded."revType"
                END,
    "order_id" = excluded."order_id",
    "amount" = excluded."amount",
    "status" = excluded."status";

  RETURN NULL;
END;
$prisma_audit$;

