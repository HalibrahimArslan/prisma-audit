CREATE OR REPLACE FUNCTION "prisma_audit_revision"() RETURNS bigint
LANGUAGE plpgsql AS $prisma_audit$
DECLARE
  revision_id bigint;
BEGIN
  -- An unset setting reads as NULL, and one reverted at the end of an earlier
  -- transaction reads as the empty string. Both mean "not published".
  revision_id := nullif(current_setting('prisma_audit.revision_id', true), '')::bigint;
  IF revision_id IS NOT NULL THEN
    RETURN revision_id;
  END IF;

  INSERT INTO "revision" ("userId", "username")
  VALUES (
    nullif(current_setting('prisma_audit.user_id', true), ''),
    nullif(current_setting('prisma_audit.username', true), '')
  )
  RETURNING "id" INTO revision_id;

  PERFORM set_config('prisma_audit.revision_id', revision_id::text, true);

  RETURN revision_id;
END;
